package org.silverpeas.core.security.authentication.exception;

/**
 * Indicates that the user's password has been successfully authenticated but a second
 * authentication factor is required before creating the Silverpeas authentication token.
 */
public class AuthenticationTwoFactorRequiredException extends AuthenticationException {

  private static final long serialVersionUID = 1L;

  public AuthenticationTwoFactorRequiredException() {
    super("Two-factor authentication is required");
  }
}
